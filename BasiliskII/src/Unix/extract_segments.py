#!/usr/bin/env python3
"""
Extract CODE segment information from a Retro68 ELF file.
Outputs a .segments file that maps segment VMA ranges and JT entries.

Usage: extract_segments.py <elf_file> [output_file]
"""

import sys
import subprocess
import re
from collections import defaultdict

def run_objdump(elf_path, *args):
    """Run objdump with the Retro68 toolchain."""
    toolchain_base = "~/.retro68/Retro68-build/toolchain/m68k-apple-macos/bin"
    objdump = f"{toolchain_base}/objdump"
    import os
    objdump = os.path.expanduser(objdump)

    cmd = [objdump] + list(args) + [elf_path]
    result = subprocess.run(cmd, capture_output=True, text=True)
    return result.stdout

def extract_segments(elf_path):
    """Extract segment info from ELF file."""

    # Get section headers
    sections_output = run_objdump(elf_path, "-h")

    segments = {}
    # Parse section headers to find .codeXXXXX sections
    # Format: Idx Name          Size      VMA       LMA       File off  Algn
    for line in sections_output.split('\n'):
        match = re.match(r'\s*\d+\s+\.code(\d+)\s+([0-9a-f]+)\s+([0-9a-f]+)', line)
        if match:
            seg_num = int(match.group(1))
            size = int(match.group(2), 16)
            vma_start = int(match.group(3), 16)
            vma_end = vma_start + size
            segments[seg_num] = {
                'vma_start': vma_start,
                'vma_end': vma_end,
                'size': size
            }

    # Get symbol table to find function VMAs
    symbols_output = run_objdump(elf_path, "-t")

    functions = []
    for line in symbols_output.split('\n'):
        # Format: 0000c450 g     F .code00002	00000018 _Z16incrementCounterv
        match = re.match(r'([0-9a-f]+)\s+[gl]\s+F\s+\.code(\d+)\s+[0-9a-f]+\s+(\S+)', line)
        if match:
            vma = int(match.group(1), 16)
            seg_num = int(match.group(2))
            name = match.group(3)
            functions.append({
                'name': name,
                'vma': vma,
                'segment': seg_num
            })

    return segments, functions

def find_jt_reference_function(segments, functions):
    """
    Find a "reference function" for each segment that we can use to calculate
    the segment's runtime base. Prefer main() or the first function in each segment.
    """
    seg_ref_funcs = {}

    for seg_num in segments:
        seg_funcs = [f for f in functions if f['segment'] == seg_num]
        if not seg_funcs:
            continue

        # Prefer main, then _start, then first function alphabetically
        main_func = next((f for f in seg_funcs if f['name'] == 'main'), None)
        start_func = next((f for f in seg_funcs if f['name'] == '_start'), None)

        if main_func:
            seg_ref_funcs[seg_num] = main_func
        elif start_func:
            seg_ref_funcs[seg_num] = start_func
        elif seg_funcs:
            # Sort by VMA and take first
            seg_ref_funcs[seg_num] = min(seg_funcs, key=lambda f: f['vma'])

    return seg_ref_funcs

def write_segments_file(output_path, segments, functions, ref_funcs):
    """Write the .segments file."""
    with open(output_path, 'w') as f:
        f.write("# Retro68 Segment Map\n")
        f.write("# Generated by extract_segments.py\n")
        f.write("# Format: SEGMENT <num> <vma_start> <vma_end>\n")
        f.write("#         REF_FUNC <segment> <vma> <name>\n")
        f.write("#         FUNC <vma> <segment> <name>\n\n")

        # Write segment VMA ranges
        for seg_num in sorted(segments.keys()):
            seg = segments[seg_num]
            f.write(f"SEGMENT {seg_num} 0x{seg['vma_start']:08x} 0x{seg['vma_end']:08x}\n")

        f.write("\n")

        # Write reference functions for each segment
        for seg_num in sorted(ref_funcs.keys()):
            func = ref_funcs[seg_num]
            f.write(f"REF_FUNC {seg_num} 0x{func['vma']:08x} {func['name']}\n")

        f.write("\n")

        # Write all functions (for breakpoint lookup)
        for func in sorted(functions, key=lambda f: f['vma']):
            f.write(f"FUNC 0x{func['vma']:08x} {func['segment']} {func['name']}\n")

def main():
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <elf_file> [output_file]")
        sys.exit(1)

    elf_path = sys.argv[1]
    output_path = sys.argv[2] if len(sys.argv) > 2 else elf_path.replace('.gdb', '.segments')
    if output_path == elf_path:
        output_path = elf_path + '.segments'

    print(f"Extracting segment info from {elf_path}...")

    segments, functions = extract_segments(elf_path)
    ref_funcs = find_jt_reference_function(segments, functions)

    print(f"Found {len(segments)} segments, {len(functions)} functions")
    for seg_num in sorted(segments.keys()):
        seg = segments[seg_num]
        ref = ref_funcs.get(seg_num)
        ref_name = ref['name'] if ref else "(none)"
        print(f"  Segment {seg_num}: 0x{seg['vma_start']:08x}-0x{seg['vma_end']:08x}, ref: {ref_name}")

    write_segments_file(output_path, segments, functions, ref_funcs)
    print(f"Wrote {output_path}")

if __name__ == '__main__':
    main()
